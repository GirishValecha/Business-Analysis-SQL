--31. Show customers whose total revenue is greater than ₹5,000. (CTE)
WITH CustomerRevenue AS	
(
	SELECT customer_id, 
			SUM(total_amount) AS Revenue 
	FROM transactions
	GROUP BY customer_id
)
SELECT * FROM CustomerRevenue 
WHERE Revenue > 5000


--32. Rank all customers by lifetime value (highest first). (Dense_Rank)
