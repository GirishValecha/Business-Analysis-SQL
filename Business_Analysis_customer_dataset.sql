--28. Categorize customers based on lifetime_value: (Case-When)
-- If lifetime_value >= 5000 → High Value
-- Otherwise → Low Value 
SELECT customer_id, lifetime_value, 
CASE
	WHEN lifetime_value >= 5000 THEN 'High Value'
	ELSE 'Low Value'
END AS customer_type 
FROM customers


--29. Categorize customers by age: (Case-When)
--| Age       | Category |
--| --------- | -------- |
--| Age >= 60 | Senior   |
--| Age >= 18 | Adult    |
--| Else      | Minor    |

SELECT customer_id, age,
CASE
	WHEN age >= 60 THEN 'Senior'
	WHEN age >= 18 THEN 'Adult'
	ELSE 'Minor'
END AS category
FROM customers
ORDER BY age ASC


--30. Show all products whose price is greater than the average price of all products. (Sub-Query)
