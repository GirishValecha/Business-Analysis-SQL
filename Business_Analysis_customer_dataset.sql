-- User Defined Function(UDF) to check voter eligibility.
CREATE FUNCTION dbo.CheckVoterEligibility
(
    @Age INT
)
RETURNS VARCHAR(20)
AS
BEGIN
    DECLARE @Result VARCHAR(20);

    IF @Age >= 18
        SET @Result = 'Eligible';
    ELSE
        SET @Result = 'Not Eligible';

    RETURN @Result;
END;

--checking result
SELECT dbo.CheckVoterEligibility(25) AS Result;


--34. Create a function called: CheckAgeGroup
-- It should take @Age INT and return:
--Senior → age >= 60
--Adult → age >= 18
--Minor → below 18

CREATE FUNCTION dbo.CheckAgeGroup
( @Age INT )
RETURNS VARCHAR(20)
AS
BEGIN
DECLARE @Result VARCHAR(20)

IF @Age > 60
	SET @Result = 'Senior'
ELSE IF @Age >= 18
	SET @Result = 'Adult'
ELSE 
	SET @Result = 'Minor'

RETURN @Result
END

